/// Drawn for any character without a glyph: an outlined box.
const FALLBACK: &str = "||#######|#.....#|#.....#|#.....#|#.....#|#.....#|#.....#|#.....#|#.....#|#######";

const fn parse(art: &str) -> [u8; HEIGHT] {
    let b = art.as_bytes();
    let mut out = [0u8; HEIGHT];
    let (mut row, mut col, mut i) = (1usize, 0usize, 0usize);
    while i < b.len() {
        let c = b[i];
        if c == b'|' {
            row += 1;
            col = 0;
        } else {
            if c == b'#' && row < HEIGHT && col < WIDTH {
                out[row] |= 0x80 >> col;
            }
            col += 1;
        }
        i += 1;
    }
    out
}

const fn build() -> [[u8; HEIGHT]; 96] {
    let mut g = [[0u8; HEIGHT]; 96];
    let mut i = 0;
    while i < 95 {
        g[i] = parse(ART[i]);
        i += 1;
    }
    g[95] = parse(FALLBACK);
    g
}

/// Bitmaps: one byte per row, most significant bit = leftmost pixel.
static GLYPHS: [[u8; HEIGHT]; 96] = build();

/// The bitmap for `c` (the fallback box for anything not printable ASCII).
pub fn glyph(c: char) -> &'static [u8; HEIGHT] {
    match c {
        ' '..='~' => &GLYPHS[c as usize - 0x20],
        _ => &GLYPHS[95],
    }
}

/// Hex digits 3 pixels wide and 5 high (rows, top first; the high bit of
/// three the leftmost), for [`wide_box`].
