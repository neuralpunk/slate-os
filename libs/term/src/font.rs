/// A wide character the font has no glyph for (ADR 0166): a box two
/// cells wide (16 pixels; bit 15 the leftmost) holding its code point in
/// hex, two rows of digits (three a row past U+FFFF).
pub fn wide_box(c: char) -> [u16; HEIGHT] {
    let mut g = [0u16; HEIGHT];
    for row in g.iter_mut().take(HEIGHT - 1).skip(1) {
        *row = 0b0100_0000_0000_0010;
    }
    g[1] = 0b0111_1111_1111_1110;
    g[HEIGHT - 2] = 0b0111_1111_1111_1110;
    let code = c as u32;
    let digits = if code > 0xFFFF { 6 } else { 4 };
    let per_row = digits / 2;
    for i in 0..digits {
        let d = (code >> (4 * (digits - 1 - i))) & 0xF;
        let (r, k) = (i / per_row, i % per_row);
        // Centred: each digit 3 wide with a gap of 1.
        let width = per_row * 4 - 1;
        let x = (16 - width) / 2 + k * 4;
        let y = 3 + r * 6;
        for (dy, bits) in HEX[d as usize].iter().enumerate() {
            g[y + dy] |= u16::from(*bits) << (13 - x);
        }
    }
    g
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wide_boxes() {
        // 中 is U+4E2D: the top row of digits shows 4 and E.
        let g = wide_box('中');
        assert_eq!(g[1], 0b0111_1111_1111_1110);
        let mask = (0b111 << 9) | (0b111 << 5);
        assert_eq!(g[3] & mask, (u16::from(HEX[4][0]) << 9) | (u16::from(HEX[0xE][0]) << 5));
        assert_eq!(g[3] & !mask, 0b0100_0000_0000_0010, "the box's sides only");
        assert_ne!(wide_box('中'), wide_box('文'));
        assert_ne!(wide_box('\u{1F600}'), wide_box('\u{1F601}'), "six digits past U+FFFF");
    }

    #[test]
    fn every_printable_char_but_space_has_pixels() {
        for c in '!'..='~' {
            assert!(glyph(c).iter().any(|&r| r != 0), "glyph {c:?} is empty");
        }
        assert!(glyph(' ').iter().all(|&r| r == 0));
    }

    #[test]
    fn glyphs_stay_in_bounds() {
        // Row 0 and column 7 stay clear so glyphs never touch.
        for c in ' '..='~' {
            let g = glyph(c);
            assert_eq!(g[0], 0, "{c:?} uses row 0");
            assert!(g.iter().all(|&r| r & 1 == 0), "{c:?} uses column 7");
        }
    }

    #[test]
    fn distinct_glyphs() {
        let mut seen = std::collections::HashMap::new();
        for c in '!'..='~' {
            if let Some(other) = seen.insert(*glyph(c), c) {
                panic!("{c:?} and {other:?} have the same bitmap");
            }
        }
    }

    #[test]
    fn fallback_for_non_ascii() {
        assert_eq!(glyph('é'), glyph('\u{1F600}'));
        assert_ne!(glyph('é'), glyph('e'));
    }

    #[test]
    fn letter_a_shape() {
        let a = glyph('A');
        assert_eq!(a[2], 0b0011_1000);
        assert_eq!(a[7], 0b1111_1110);
    }
}
