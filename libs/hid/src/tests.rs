const G900_KEYS: &[u8] = &[
    0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x85, 0x01, 0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25, 0x01, 0x75,
    0x01, 0x95, 0x08, 0x81, 0x02, 0x81, 0x03, 0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x26, 0xa4, 0x00, 0x19, 0x00, 0x2a,
    0xa4, 0x00, 0x81, 0x00, 0xc0, 0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, 0x85, 0x03, 0x75, 0x10, 0x95, 0x02, 0x15, 0x01,
    0x26, 0x8c, 0x02, 0x19, 0x01, 0x2a, 0x8c, 0x02, 0x81, 0x00, 0xc0, 0x05, 0x01, 0x09, 0x80, 0xa1, 0x01, 0x85, 0x04,
    0x75, 0x02, 0x95, 0x01, 0x15, 0x01, 0x25, 0x03, 0x09, 0x82, 0x09, 0x81, 0x09, 0x83, 0x81, 0x60, 0x75, 0x06, 0x81,
    0x03, 0xc0, 0x06, 0x00, 0xff, 0x09, 0x01, 0xa1, 0x01, 0x85, 0x10, 0x75, 0x08, 0x95, 0x06, 0x15, 0x00, 0x26, 0xff,
    0x00, 0x09, 0x01, 0x81, 0x00, 0x09, 0x01, 0x91, 0x00, 0xc0, 0x06, 0x00, 0xff, 0x09, 0x02, 0xa1, 0x01, 0x85, 0x11,
    0x75, 0x08, 0x95, 0x13, 0x15, 0x00, 0x26, 0xff, 0x00, 0x09, 0x02, 0x81, 0x00, 0x09, 0x02, 0x91, 0x00, 0xc0,
];

#[test]
fn keys_consumer_and_system_controls() {
    assert_eq!(G900_KEYS.len(), 151);
    let d = parse(G900_KEYS).unwrap();
    assert!(d.report_ids);
    assert_eq!(
        d.applications,
        [
            usage(PAGE_GENERIC_DESKTOP, GD_KEYBOARD),
            usage(PAGE_CONSUMER, 1),
            usage(PAGE_GENERIC_DESKTOP, 0x80),
            usage(0xFF00, 1),
            usage(0xFF00, 2)
        ]
    );
    let key = |id| usage(PAGE_KEYBOARD, id);
    // Left Shift and A.
    assert_eq!(d.pressed(1, &[0x02, 0, 0x04, 0, 0, 0, 0, 0]), Some(std::vec![key(0x04), key(0xE1)]));
    assert_eq!(d.pressed(1, &[0; 8]), Some(std::vec![]));
    // Phantom state: every slot ErrorRollOver.
    assert_eq!(d.pressed(1, &[0, 0, 1, 1, 1, 1, 1, 1]), None);
    // Volume Up; then nothing (0 is below the logical minimum of 1).
    assert_eq!(d.pressed(3, &[0xE9, 0x00, 0, 0]), Some(std::vec![usage(PAGE_CONSUMER, 0xE9)]));
    assert_eq!(d.pressed(3, &[0, 0, 0, 0]), Some(std::vec![]));
    // System Power Down is the array's second value.
    assert_eq!(d.pressed(4, &[0x02]), Some(std::vec![usage(PAGE_GENERIC_DESKTOP, 0x81)]));
    assert_eq!(d.pressed(4, &[0x00]), Some(std::vec![]));
    // The vendor reports' bytes name no controls.
    assert_eq!(d.pressed(0x10, &[1, 2, 3, 4, 5, 6]), Some(std::vec![]));
}
