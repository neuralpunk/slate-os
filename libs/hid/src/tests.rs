use super::*;

/// HID 1.11 appendix E.10: the boot mouse's report descriptor.
const BOOT_MOUSE: &[u8] = &[
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25,
    0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01, 0x05, 0x01, 0x09, 0x30, 0x09, 0x31,
    0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06, 0xC0, 0xC0,
];

/// An absolute pointer as virtual machines offer: report ID 1, three
/// buttons, X and Y from 0 to 32767 in 16 bits, a relative wheel.
const TABLET: &[u8] = &[
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15,
    0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01, 0x05, 0x01, 0x09, 0x30,
    0x09, 0x31, 0x15, 0x00, 0x26, 0xFF, 0x7F, 0x35, 0x00, 0x46, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0x05,
    0x01, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x35, 0x00, 0x45, 0x00, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06, 0xC0, 0xC0,
];

#[test]
fn boot_mouse() {
    let d = parse(BOOT_MOUSE).unwrap();
    assert!(!d.report_ids);
    assert_eq!(d.applications, [usage(PAGE_GENERIC_DESKTOP, GD_MOUSE)]);
    assert_eq!(d.report_len(Kind::Input, 0), 3);
    let (x, xi) = d.find_input(usage(PAGE_GENERIC_DESKTOP, GD_X)).unwrap();
    let (y, yi) = d.find_input(usage(PAGE_GENERIC_DESKTOP, GD_Y)).unwrap();
    assert!(x.is_relative() && x.offset == 8 && x.size == 8);
    // Buttons 1 and 3, X -3, Y +5.
    let report = [0b101, 0xFD, 0x05];
    assert_eq!((x.value(&report, xi), y.value(&report, yi)), (Some(-3), Some(5)));
    let (b, bi) = d.find_input(usage(PAGE_BUTTON, 3)).unwrap();
    assert_eq!(b.value(&report, bi), Some(1));
    let (b, bi) = d.find_input(usage(PAGE_BUTTON, 2)).unwrap();
    assert_eq!(b.value(&report, bi), Some(0));
}

#[test]
fn absolute_tablet() {
    let d = parse(TABLET).unwrap();
    assert!(d.report_ids);
    let (x, xi) = d.find_input(usage(PAGE_GENERIC_DESKTOP, GD_X)).unwrap();
    assert!(!x.is_relative());
    assert_eq!((x.logical_min, x.logical_max, x.report_id, x.offset, x.size), (0, 32767, 1, 8, 16));
    let (w, wi) = d.find_input(usage(PAGE_GENERIC_DESKTOP, GD_WHEEL)).unwrap();
    assert!(w.is_relative());
    assert_eq!(d.report_len(Kind::Input, 1), 6);
    // After the ID byte: no buttons, X 16384, Y 8192, wheel -1.
    let data = [0, 0x00, 0x40, 0x00, 0x20, 0xFF];
    assert_eq!(x.value(&data, xi), Some(16384));
    let (y, yi) = d.find_input(usage(PAGE_GENERIC_DESKTOP, GD_Y)).unwrap();
    assert_eq!(y.value(&data, yi), Some(8192));
    assert_eq!(w.value(&data, wi), Some(-1));
}

#[test]
fn broken_descriptors() {
    assert_eq!(parse(&[0x05]), Err(Error::Truncated));
    assert_eq!(parse(&[0xC0]), Err(Error::Malformed));
    assert_eq!(parse(&[0xB4]), Err(Error::Malformed));
    // A long item is skipped.
    assert_eq!(parse(&[0xFE, 2, 0x10, 0xAA, 0xBB, 0x05, 0x01]).map(|d| d.fields.len()), Ok(0));
}

/// A Logitech G900 mouse's second interface (046d:c081, read from the
/// device under Fedora on the reference PC, 2026-10-23): a keyboard (report 1:
/// modifiers, a reserved byte, six keys), consumer controls (report 3: two
